        $(document).ready(function() {
            $('#dni').on('blur', function() {
                var dni = $(this).val();
                if (dni.length === 8 && $.isNumeric(dni)) {
                    $.ajax({
                        url: '<?= site_url("api/consulta_dni") ?>',
                        type: 'POST',
                        contentType: 'application/json',
                        data: JSON.stringify({
                            dni: dni
                        }),
                        success: function(response) {
                            if (response.success) {
                                $('input[name="name"]').val(response.nombres);
                                $('input[name="lastname"]').val(response.apellidoPaterno);
                                $('input[name="motherLast"]').val(response.apellidoMaterno);
                            } else {
                                // Puedes mostrar un mensaje o limpiar los campos
                                $('input[name="name"], input[name="lastname"], input[name="motherLast"]')
                                    .val('');
                                alert(response.message);
                            }
                        },
                        error: function() {
                            $('input[name="name"], input[name="lastname"], input[name="motherLast"]')
                                .val('');
                            alert('Error al consultar el DNI.');
                        }
                    });
                }
            });
        });
